ALTER TABLE public.nocode_object RENAME COLUMN updated_at TO update_time;
ALTER TABLE public.nocode_object_version RENAME COLUMN created_by TO creator;
ALTER TABLE public.nocode_object_version RENAME COLUMN created_at TO create_time;
ALTER TABLE public.nocode_object ALTER COLUMN creator TYPE varchar(64) USING creator::text,
  ALTER COLUMN updater TYPE varchar(64) USING updater::text,
  ALTER COLUMN create_time TYPE timestamp(6) without time zone USING create_time AT TIME ZONE 'Asia/Shanghai',
  ALTER COLUMN update_time TYPE timestamp(6) without time zone USING update_time AT TIME ZONE 'Asia/Shanghai';
